const BASE = `${import.meta.env.BASE_URL}cars/`

// Адрес фото машины: номер с единицы, small — уменьшенная копия, если она есть
export function carPhotoUrl(id: string, number: number, small = false) {
  const name = String(number).padStart(2, '0')
  return `${BASE}${id}/${name}${small && CAR_PHOTOS[id]?.[1] ? '-sm' : ''}.webp`
}

// srcset фото машины: уменьшенная копия вдвое уже большого кадра
export function carPhotoSrcSet(id: string, number: number) {
  const [, hasSmall, width] = CAR_PHOTOS[id] ?? [0, false, 0]
  if (!hasSmall || !width) return undefined
  return `${carPhotoUrl(id, number, true)} ${width / 2}w, ${carPhotoUrl(id, number)} ${width}w`
}
